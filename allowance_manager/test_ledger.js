'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const L = require('./ledger.js');
const original = L.newState();
assert.deepEqual(original, { version: 1, monthlyBudget: null, transactions: [] });
const configured = L.setBudget(original, 30000);
assert.equal(original.monthlyBudget, null);
const expense = { id: '11111111-1111-4111-8111-111111111111', date: '2026-11-05', kind: 'expense', amount: 2500, category: '食品', note: '昼食' };
const income = { id: '22222222-2222-4222-8222-222222222222', date: '2026-11-06', kind: 'income', amount: 5000, category: '入金', note: '臨時収入' };
const old = { ...expense, id: '33333333-3333-4333-8333-333333333333', date: '2026-10-31', amount: 700 };
let state = L.add(L.add(L.add(configured, expense), income), old);
const result = L.summary(state, '2026-11');
assert.equal(result.spent, 2500);
assert.equal(result.income, 5000);
assert.equal(result.budget, 35000);
assert.equal(result.remaining, 32500);
assert.equal(result.categories.find(x => x.name === '食品').amount, 2500);
assert.equal(result.entries.length, 2);
assert.equal(L.summary(state, '2026-10').spent, 700);
state = L.remove(state, expense.id);
assert.equal(L.summary(state, '2026-11').remaining, 35000);
assert.throws(() => L.remove(state, expense.id), /does not exist/);
assert.throws(() => L.date('2026-02-30'), /calendar date/);
assert.throws(() => L.month('2026-13'), /Invalid month/);
assert.throws(() => L.parseYen('0', '金額'), /整数/);
assert.throws(() => L.parseYen('3.2', '金額'), /整数/);
assert.throws(() => L.parseYen('10000001', '金額'), /integer/);
assert.throws(() => L.validate({ ...configured, version: 2 }), /version/);
assert.throws(() => L.validate({ ...configured, extra: 1 }), /fields/);
assert.throws(() => L.validate({ ...configured, transactions: [expense, expense] }), /duplicate/);
assert.throws(() => L.add(configured, { ...expense, category: '謎' }), /category/);
assert.throws(() => L.add(configured, { ...income, category: '食品' }), /category/);
assert.throws(() => L.add(configured, { ...expense, note: 'x'.repeat(61) }), /note/);
assert.equal(L.summary(L.add(L.setBudget(original, 10), expense), '2026-11').remaining, -2490);
const html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');
const app = fs.readFileSync(path.join(__dirname, 'app.js'), 'utf8');
for (const id of ['status', 'month', 'current-month', 'remaining', 'budget-total', 'spent-caption', 'progress', 'progress-fill', 'donut', 'donut-total', 'legend', 'recent-list', 'transaction-list', 'history-empty', 'monthly-budget', 'save-budget', 'mode-expense', 'mode-income', 'entry-date', 'entry-amount', 'entry-category', 'entry-note', 'add-entry']) {
  assert.ok(html.includes('id="' + id + '"'), 'missing UI element ' + id);
}
assert.deepEqual([...html.matchAll(/data-page="([^"]+)"/g)].map(m => m[1]), ['home', 'record', 'history', 'settings']);
assert.deepEqual([...html.matchAll(/class="nav-button(?: active)?" type="button" data-view="([^"]+)"/g)].map(m => m[1]), ['home', 'record', 'history', 'settings']);
assert.match(html, /conic-gradient|id="donut"/, 'must show category donut');
assert.match(html, /@media\(max-width:360px\)/, 'mobile layout must be responsive');
assert.match(app, /window\.minapp\.userState\.set/);
assert.match(app, /window\.addEventListener\('minappready'/);
assert.doesNotMatch(app, /localStorage|sessionStorage|setTimeout/);
console.log('allowance_manager: all domain and UI contract tests passed');
